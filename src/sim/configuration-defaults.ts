/** Defaults are a shared reference, never mutable global state. Drafts are copied
 * before editing; persisted candidates are frozen only after validation. */
export function freezeConfiguration<T>(value: T): T {
  if (value !== null && typeof value === 'object' && !Object.isFrozen(value)) {
    for (const child of Object.values(value)) freezeConfiguration(child)
    Object.freeze(value)
  }
  return value
}
